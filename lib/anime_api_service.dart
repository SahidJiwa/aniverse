        return malId;
      }
      // ignore: avoid_print
      print('🟠 RESOLVE-CHECK: AniList found no idMal for "$title", trying Jikan');
    } catch (e) {
      // ignore: avoid_print
      print('🟠 RESOLVE-CHECK: AniList search threw for "$title" -> $e, trying Jikan');
    }

    // Fallback: Jikan title search.
    try {
      // ignore: avoid_print
      print('🟠 RESOLVE-CHECK: searching Jikan for title "$title"...');
      final res = await _jikanGet(
          '$_jikanBase/anime?q=${Uri.encodeComponent(title)}&limit=1&sfw=true');
      // ignore: avoid_print
      print('🟠 RESOLVE-CHECK: Jikan responded status=${res.statusCode} bodyLen=${res.body.length}');
      final decoded = jsonDecode(res.body) as Map<String, dynamic>;
      final data = decoded['data'] as List<dynamic>? ?? [];
      if (data.isEmpty) {
        // ignore: avoid_print
        print('🟠 RESOLVE-CHECK: no results for "$title"');
        _resolvedMalIdCache[key] = null;
        return null;
      }
      final first = data.first as Map<String, dynamic>;
      final malId = first['mal_id']?.toString();
      // ignore: avoid_print
      print('🟠 RESOLVE-CHECK: Jikan resolved "$title" -> malId=$malId');
      _resolvedMalIdCache[key] = malId;
      return malId;
    } catch (e) {
      // ignore: avoid_print
      print('🟠 RESOLVE-CHECK: threw for "$title" -> $e');
      _resolvedMalIdCache[key] = null;
      return null;
    }
  }

  // ── Cover by title — Jikan search, take first result's image ────────────
  static final Map<String, Future<String?>> _coverInFlight = {};

  static Future<String?> fetchCoverByTitle(String title) async {
    final key = title.trim().toLowerCase();
    if (key.isEmpty || key.startsWith('custom-')) return null;
    if (_coverCache.containsKey(key)) return _coverCache[key];
    return _coverInFlight.putIfAbsent(key, () => _fetchCoverByTitle(key, title));
  }

  static Future<String?> _fetchCoverByTitle(String key, String title) async {
    try {
      // AniList first — separate CDN from MAL's, already CORS-friendly, and
      // not subject to the Jikan 504s currently seen when MAL's own upstream
      // is overloaded. See file header / ProxiedNetworkImage for why this
      // matters: the whole point of this fallback is to escape MAL's CDN,
      // so searching MAL (Jikan) again first defeats the purpose.
      //
      // NOTE: deliberately NOT reusing _searchAnimeFromAniList() here — that
      // helper (via _mapAniListPage) discards any result missing an idMal,
      // which is meant for building full AnimeModel list entries. Here we
      // only need a cover image, so a result without idMal is still usable
      // and skipping it was silently causing generic-title searches (e.g.
      // "Attack on Titan", "Jujutsu Kaisen") to fall through to Jikan/
      // placeholder even though AniList had a perfectly good cover.
      try {
        final data = await _aniListQuery(_aniListCoverOnlyQuery, {
          'search': title,
          'perPage': 5,
        });
        final mediaList = (data?['Page'] as Map<String, dynamic>?)?['media']
                as List<dynamic>? ??
            [];
        for (final item in mediaList) {
          final m = item as Map<String, dynamic>;
          final cover = m['coverImage'] as Map<String, dynamic>? ?? {};
          final url =
              (cover['extraLarge'] as String?) ?? (cover['large'] as String?);
          if (url != null && url.isNotEmpty) {
            _coverCache[key] = url;
            return url;
          }
        }
      } catch (e) {
        developer.log('[fetchCoverByTitle] AniList failed for "$title": $e',
            name: 'AnimeApiService', level: 900);
      }

      // Jikan fallback — only reached if AniList had nothing.
      final res = await _jikanGet(
          '$_jikanBase/anime?q=${Uri.encodeComponent(title)}&limit=1&sfw=true');
      final decoded = jsonDecode(res.body) as Map<String, dynamic>;
      final data = decoded['data'] as List<dynamic>? ?? [];
      if (data.isEmpty) {
        _coverCache[key] = null;
        return null;
      }
      final first = data.first as Map<String, dynamic>;
      final images = first['images'] as Map<String, dynamic>? ?? {};
      final jpg = images['jpg'] as Map<String, dynamic>? ?? {};
      final url = (jpg['large_image_url'] as String?) ?? (jpg['image_url'] as String?);
      _coverCache[key] = url;
      return url;
    } catch (_) {
      _coverCache[key] = null;
      return null;
    } finally {
      _coverInFlight.remove(key);
    }
  }

