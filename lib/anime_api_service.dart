  static List<AnimeModel> _mapAniListPage(Map<String, dynamic>? data) {
    final mediaList = (data?['Page'] as Map<String, dynamic>?)?['media'] as List<dynamic>? ?? [];
    final result = <AnimeModel>[];
    for (final item in mediaList) {
      final m = item as Map<String, dynamic>;
      final idMal = m['idMal'];
      if (idMal == null) continue; // no MAL id → can't key into the rest of the app
      final id = idMal.toString();
      final t = m['title'] as Map<String, dynamic>? ?? {};
      final title = (t['english'] as String?)?.trim().isNotEmpty == true
          ? (t['english'] as String).trim()
          : ((t['romaji'] as String?)?.trim() ?? 'Unknown Title');
      final cover = m['coverImage'] as Map<String, dynamic>? ?? {};
      final image = (cover['extraLarge'] as String?) ??
          (cover['large'] as String?) ??
          'https://placehold.co/600x800/png?text=No+Image';
      final score = ((m['averageScore'] as num?)?.toDouble() ?? 0.0) / 10.0;
      final genres = (m['genres'] as List<dynamic>? ?? []).whereType<String>().toList();
      final synopsis = ((m['description'] as String?) ?? '')
          .replaceAll(RegExp(r'<[^>]*>'), '')
          .trim();
      final popularity = (m['popularity'] as num?)?.toInt() ?? 0;

      result.add(AnimeModel(
        id: id,
        title: title,
        imageUrl: image,
        rating: score,
        genres: genres.isEmpty ? const ['Unknown'] : genres,
        description: synopsis.isEmpty ? 'No synopsis available.' : synopsis,
        isTrending: popularity >= 50000,
        episodes: const [],
        malId: int.tryParse(id),
      ));
    }
    return result;
  }

  /// AniList uses YYYY + a season enum (WINTER/SPRING/SUMMER/FALL) rather
  /// than Jikan's "now" shorthand, so the current season has to be computed
  /// on our side the same way AniList itself buckets months.
  static String _currentAniListSeasonName() {
    final month = DateTime.now().month;
    if (month <= 3) return 'WINTER';
    if (month <= 6) return 'SPRING';
    if (month <= 9) return 'SUMMER';
    return 'FALL';
  }

