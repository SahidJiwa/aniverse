// ---------------------------------------------------------------------------
// AnimeApiService — Jikan (MyAnimeList) only.
//
// Sebelumnya app ini pakai AniList GraphQL (lewat proxy Cloudflare Worker
// pihak ketiga) untuk detail/recommendations/characters, dan Jikan hanya
// untuk episodes. Proxy itu menolak request dari Flutter Web (403), dan
// AniList langsung tanpa proxy juga rawan CORS di browser.
//
// Jikan sudah terbukti CORS-friendly untuk browser (episodes selalu
// berhasil load) dan menyediakan semua data yang dibutuhkan (detail,
// recommendations, characters + voice actors, reviews) dalam satu API —
// jadi seluruh service sekarang Jikan-only. Tidak ada lagi MAL↔AniList ID
// mapping, tidak ada lagi proxy pihak ketiga.
// ---------------------------------------------------------------------------

class AnimeApiService {
  static bool get isTestMode => false;

  static const _jikanBase = 'https://api.jikan.moe/v4';

  // ── Memory cache ─────────────────────────────────────────────────────────
  static final Map<String, List<AnimeModel>>      _listCache    = {};
  static final Map<String, JikanAnimeDetail>       _detailCache  = {};
  static final Map<String, List<CharacterModel>>   _charCache    = {};
  static final Map<String, List<VoiceActorModel>>  _vaCache      = {};
  static final Map<String, List<AnimeModel>>       _recoCache    = {};
  static final Map<String, List<EpisodeModel>>     _episodeCache = {};
  static final Map<String, String?>                _coverCache   = {};

  // ── Jikan rate-limit guard ────────────────────────────────────────────
  // Jikan's own docs require a minimum 4-second gap between requests for
  // normal (non-bulk) usage. The previous 420ms gap was far below that,
  // which very likely contributed to the 429/504 responses seen under any
  // concurrent load (detail + episodes + characters + recommendations all
  // firing together from one screen).
  static DateTime _lastJikanRequest = DateTime.fromMillisecondsSinceEpoch(0);
  // Jikan's documented limit is roughly 3 req/s with a small burst
  // allowance — 1500ms was already conservative on paper, but with a whole
  // grid of posters (20-30+) queued behind the same mutex, a single UI
  // screen alone could sustain a rate close to that limit for tens of
  // seconds straight, with no room left for any other screen's requests
  // sharing the queue. That's what produced the wall of 504s seen in
  // testing: not one-off overload, but this app's own traffic saturating
  // Jikan's window. 2500ms trades some speed for headroom, so a full grid
  // of posters actually finishes near Jikan's real capacity instead of
  // constantly getting bounced by it.
  static const _jikanGap = Duration(milliseconds: 2500);

  // Serialized via a chained-Future mutex: every _jikanGet call awaits the
  // previous one before running, so concurrent calls (e.g. detail +
  // episodes + characters + recommendations all fired from initState at
  // once) are truly one-at-a-time — not just spaced by a timestamp check,
  // which is racy when several calls start in the same event-loop tick.
  static Future<void> _jikanQueue = Future.value();

  static Future<http.Response> _jikanGet(String url) {
    final result = _jikanQueue.then((_) => _jikanGetSerial(url));
    // Swallow errors here so one failed request doesn't break the queue for
    // requests queued after it; each caller still sees its own error below.
    _jikanQueue = result.then((_) => null, onError: (_) => null);
    return result;
  }

  static Future<http.Response> _jikanGetSerial(String url) async {
    final elapsed = DateTime.now().difference(_lastJikanRequest);
    if (elapsed < _jikanGap) {
      await Future<void>.delayed(_jikanGap - elapsed);
    }
    _lastJikanRequest = DateTime.now();
    developer.log('[Jikan] GET $url', name: 'AnimeApiService');

    http.Response res;
    try {
      res = await http.get(Uri.parse(url)).timeout(const Duration(seconds: 12));
    } catch (e) {
      developer.log('[Jikan] Network error: $e', name: 'AnimeApiService', level: 1000);
      throw Exception('Jikan network error: $e');
    }

    // The AniList fallback below turned out to be fragile in a way Jikan
    // itself never is: AniList has both a hard rate limit (429) AND a
    // manual-IP-block policy for sustained bursts (see their docs — "we
    // will manually block your IP" — which is what happened during
    // testing and can take hours to clear, not seconds). Every request
    // this app fails to get from Jikan is a request that goes to that
    // fragile fallback, so it's worth spending ONE retry here — after the
    // exact gap Jikan itself expects — to recover from a transient
    // 429/5xx before giving up on the API that's actually reliable long
    // term and falling through to the one that isn't.
    if (res.statusCode == 429 || res.statusCode >= 500) {
      // ignore: avoid_print
      print('[Jikan] ${res.statusCode} for $url — retrying once after gap');
      developer.log('[Jikan] ${res.statusCode} — retrying once after gap',
          name: 'AnimeApiService');
      await Future<void>.delayed(_jikanGap);
      _lastJikanRequest = DateTime.now();
      try {
        res = await http.get(Uri.parse(url)).timeout(const Duration(seconds: 12));
      } catch (e) {
        developer.log('[Jikan] Retry network error: $e', name: 'AnimeApiService', level: 1000);
        throw Exception('Jikan network error on retry: $e');
      }
      if (res.statusCode == 429 || res.statusCode >= 500) {
        // ignore: avoid_print
        print('[Jikan] ${res.statusCode} for $url again after retry — failing to fallback');
        developer.log('[Jikan] ${res.statusCode} again after retry — failing to fallback',
            name: 'AnimeApiService');
      }
    }

    if (res.statusCode != 200) {
      // ignore: avoid_print
      print('[Jikan] HTTP ${res.statusCode} for $url');
      developer.log('[Jikan] HTTP ${res.statusCode}: ${res.body.substring(0, res.body.length.clamp(0, 300))}',
          name: 'AnimeApiService', level: 1000);
      throw Exception('Jikan HTTP ${res.statusCode} — $url');
    }
    return res;
  }

  // ── AniList fallback ──────────────────────────────────────────────────
  // Used only when Jikan itself fails (network error, 429/504 after retry,
  // etc.) — Jikan stays the primary source everywhere. AniList's GraphQL
  // API can be queried directly by MAL id (idMal), so no separate
  // MAL↔AniList id mapping table is needed.
  static const _aniListBase = 'https://graphql.anilist.co';

  // Direct requests to graphql.anilist.co from Flutter Web get blocked by
  // the browser's CORS policy (AniList sends no Access-Control-Allow-Origin
  // header for this origin) — confirmed via DevTools console:
  // "Access to fetch at 'https://graphql.anilist.co/' ... has been blocked
  // by CORS policy". Went through proxy.corsfix.com for a while, which
  // fixed the CORS block but is a proxy SHARED with every other app using
  // it — its rate limit (429s seen in testing) reacts to everyone's
  // traffic, not just this app's, so it wasn't actually a fix for the
  // underlying rate-limit problem, just a different flavor of it.
  //
  // Final fix: same self-hosted Cloudflare Worker used for MAL images
  // above (aniverse-proxy.tirtasisahid.workers.dev/anilist — see
  // worker.js), used only by AniVerse. No shared rate limit with other
  // apps; the mutex below is what actually prevents this app's OWN
  // requests from bursting AniList's per-IP limit (the Worker's IP, now,
  // consistently — not the browser's).
  static const _aniListProxyBase =
      'https://aniverse-proxy.tirtasisahid.workers.dev/anilist';

  // Same problem Jikan already solved above, one level further down the
  // fallback chain: when Jikan fails fast (by design, no retry — see
  // _jikanGetSerial) for a whole grid of posters at once, every one of
  // them calls fetchCoverByTitle → _aniListQuery in the same event-loop
  // tick, with no spacing between them at all. AniList's rate limit reacts
  // to that burst by 429-ing nearly all of them, and the per-call
  // 3-attempt/500-1200ms backoff below isn't enough headroom to absorb a
  // burst of 20-30 simultaneous requests — it just staggers the SAME
  // burst-sized wall of retries into the next window, which gets 429'd
  // again. A serial mutex queue (identical in spirit to _jikanQueue above)
  // fixes this at the source: only one AniList request is ever in flight
  // at a time, so this fallback stops recreating the exact burst pattern
  // it exists to work around.
  static Future<void> _aniListQueue = Future.value();
  static DateTime _lastAniListRequest = DateTime.fromMillisecondsSinceEpoch(0);
  static const _aniListGap = Duration(milliseconds: 1500);

  static Future<Map<String, dynamic>?> _aniListQuery(
      String query, Map<String, dynamic> variables) {
    final result = _aniListQueue.then((_) => _aniListQuerySerial(query, variables));
    // Swallow errors here so one failed request doesn't break the queue for
    // requests queued after it; each caller still sees its own null/result.
    _aniListQueue = result.then((_) => null, onError: (_) => null);
    return result;
  }

  static Future<Map<String, dynamic>?> _aniListQuerySerial(
      String query, Map<String, dynamic> variables) async {
    final elapsed = DateTime.now().difference(_lastAniListRequest);
    if (elapsed < _aniListGap) {
      await Future<void>.delayed(_aniListGap - elapsed);
    }
    _lastAniListRequest = DateTime.now();

    // A 429 here (despite the serial mutex above) means AniList's window
    // was already tight from other traffic — treated the same as any other
    // non-200 used to mean giving up for good immediately, dropping exactly
    // the requests AniList was asking us to slow down and retry. Retrying
    // after a short backoff instead lets those requests succeed once
    // AniList's window clears, rather than treating a temporary "slow down"
    // as a permanent "no".
    const maxAttempts = 3;
    for (var attempt = 0; attempt < maxAttempts; attempt++) {
      try {
        final res = await http
            .post(
              Uri.parse(_aniListProxyBase),
              headers: {
                'Content-Type': 'application/json',
                'Accept': 'application/json',
              },
              body: jsonEncode({'query': query, 'variables': variables}),
            )
            .timeout(const Duration(seconds: 12));
        if (res.statusCode == 429) {
          if (attempt == maxAttempts - 1) {
            developer.log('[AniList] HTTP 429, out of retries',
                name: 'AnimeApiService', level: 900);
            return null;
          }
          // Exponential-ish backoff (500ms, 1200ms) plus jitter so a whole
          // batch of throttled requests doesn't retry in perfect lockstep
          // and immediately re-trigger the same rate limit.
          final backoffMs = 500 * (attempt + 1) + Random().nextInt(300);
          await Future.delayed(Duration(milliseconds: backoffMs));
          continue;
        }
        if (res.statusCode != 200) {
          developer.log('[AniList] HTTP ${res.statusCode}', name: 'AnimeApiService', level: 900);
          return null;
        }
        final decoded = jsonDecode(res.body) as Map<String, dynamic>;
        return decoded['data'] as Map<String, dynamic>?;
      } catch (e) {
        developer.log('[AniList] error: $e', name: 'AnimeApiService', level: 900);
        return null;
      }
    }
    return null;
  }

  static const _aniListDetailQuery = r'''
query ($idMal: Int) {
  Media(idMal: $idMal, type: ANIME) {
    title { english romaji }
    description(asHtml: false)
    averageScore
    episodes
    status
    genres
    studios(isMain: true) { nodes { name } }
    coverImage { extraLarge large }
    trailer { id site }
    relations {
      edges {
        relationType
        node { idMal type title { english romaji } }
      }
    }
  }
}
''';

  static Future<JikanAnimeDetail?> _fetchAnimeDetailFromAniList(String malId) async {
    final idMal = int.tryParse(malId);
    if (idMal == null) return null;
    final data = await _aniListQuery(_aniListDetailQuery, {'idMal': idMal});
    final media = data?['Media'] as Map<String, dynamic>?;
    if (media == null) return null;

    final titleMap = media['title'] as Map<String, dynamic>? ?? {};
    final titleEn = (titleMap['english'] as String?)?.trim();
    final title = (titleEn?.isNotEmpty == true)
        ? titleEn!
        : ((titleMap['romaji'] as String?)?.trim() ?? 'Unknown Title');

    final synopsis = ((media['description'] as String?) ?? '')
        .replaceAll(RegExp(r'<[^>]*>'), '')
        .trim();

    final score = ((media['averageScore'] as num?)?.toDouble() ?? 0.0) / 10.0;
    final episodes = (media['episodes'] as num?)?.toInt();
    final status = (media['status'] as String?)?.trim() ?? 'Unknown';
    final genres = (media['genres'] as List<dynamic>? ?? []).whereType<String>().toList();

    final studioNodes =
        (media['studios'] as Map<String, dynamic>?)?['nodes'] as List<dynamic>? ?? [];
    final studios = studioNodes
        .whereType<Map<String, dynamic>>()
        .map((s) => (s['name'] as String?)?.trim())
        .whereType<String>()
        .toList();

    final cover = media['coverImage'] as Map<String, dynamic>? ?? {};
    final largeImageUrl = (cover['extraLarge'] as String?) ??
        (cover['large'] as String?) ??
        'https://placehold.co/600x800/png?text=No+Image';

    final trailer = media['trailer'] as Map<String, dynamic>?;
    final trailerYoutubeId = (trailer?['site'] == 'youtube')
        ? (trailer?['id'] as String?)
        : null;

    final relEdges = (media['relations'] as Map<String, dynamic>?)?['edges'] as List<dynamic>? ?? [];
    final relations = <RelatedAnimeModel>[];
    for (final edge in relEdges) {
      final e = edge as Map<String, dynamic>;
      final node = e['node'] as Map<String, dynamic>? ?? {};
      if (node['type'] != 'ANIME') continue;
      final relId = node['idMal']?.toString() ?? '';
      if (relId.isEmpty) continue;
      final t = node['title'] as Map<String, dynamic>? ?? {};
      final relTitle = (t['english'] as String?) ?? (t['romaji'] as String?) ?? 'Unknown';
      relations.add(RelatedAnimeModel(
        malId: relId,
        title: relTitle,
        imageUrl: 'https://placehold.co/600x400/png?text=${Uri.encodeComponent(relTitle)}',
        relationType: (e['relationType'] as String?) ?? 'Related',
      ));
      if (relations.length >= 15) break;
    }

    return JikanAnimeDetail(
      title: title,
      synopsis: synopsis.isEmpty ? 'No synopsis available.' : synopsis,
      score: score,
      rank: null,
      episodes: episodes,
      status: status,
      genres: genres.isEmpty ? const ['Unknown'] : genres,
      studios: studios,
      largeImageUrl: largeImageUrl,
      trailerYoutubeId: trailerYoutubeId,
      relations: relations,
    );
  }

