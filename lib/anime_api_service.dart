  // ── AniList Page fallback for list endpoints ─────────────────────────────
  // Used when Jikan's list endpoints (seasons/now, top/anime, anime?genres=,
  // anime?q=) fail outright — e.g. the 504s seen when Jikan's upstream is
  // overloaded. Unlike the single-Media detail queries above, these hit
  // AniList's `Page` connection to get back a list shaped like Jikan's,
