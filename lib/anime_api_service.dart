  // don't need to know which source actually answered.
  static const _aniListPageQuery = r'''
query ($search: String, $season: MediaSeason, $seasonYear: Int, $genre: String, $sort: [MediaSort], $perPage: Int) {
  Page(perPage: $perPage) {
    media(type: ANIME, search: $search, season: $season, seasonYear: $seasonYear, genre: $genre, sort: $sort) {
      idMal
      title { english romaji }
