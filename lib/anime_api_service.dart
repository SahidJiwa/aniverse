  // ── Helper: map a Jikan "data" anime object → AnimeModel ─────────────────
  static AnimeModel _mapJikanAnime(Map<String, dynamic> m) {
    final id = m['mal_id']?.toString() ?? '';
    final titleMap = m['titles'] as List<dynamic>? ?? [];
    String? titleEn = (m['title_english'] as String?)?.trim();
    String? titleDefault = (m['title'] as String?)?.trim();
    if ((titleEn == null || titleEn.isEmpty) && titleMap.isNotEmpty) {
      titleEn = titleMap
          .whereType<Map<String, dynamic>>()
          .firstWhere((t) => t['type'] == 'English', orElse: () => {})['title']
          as String?;
    }
    final title = (titleEn?.isNotEmpty == true)
        ? titleEn!
        : (titleDefault?.isNotEmpty == true ? titleDefault! : 'Unknown Title');

    final images = m['images'] as Map<String, dynamic>? ?? {};
    final jpg = images['jpg'] as Map<String, dynamic>? ?? {};
    final cover = (jpg['large_image_url'] as String?) ??
        (jpg['image_url'] as String?) ??
        'https://placehold.co/600x800/png?text=No+Image';

    final rawScore = (m['score'] as num?)?.toDouble();
    final score = rawScore ?? 0.0;

    final genresList = (m['genres'] as List<dynamic>? ?? [])
        .whereType<Map<String, dynamic>>()
        .map((g) => (g['name'] as String?)?.trim())
        .whereType<String>()
        .toList();

    final synopsis = (m['synopsis'] as String?)?.trim() ?? '';
    final members = (m['members'] as num?)?.toInt() ?? 0;

    return AnimeModel(
      id: id,
      title: title,
      imageUrl: cover,
      rating: score,
      genres: genresList.isEmpty ? const ['Unknown'] : genresList,
      description: synopsis.isEmpty ? 'No synopsis available.' : synopsis,
      isTrending: members >= 200000,
      episodes: const [],
      malId: int.tryParse(id),
    );
  }

