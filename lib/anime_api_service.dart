  // Used as a fallback for latest-aired-episode number when Jikan's
  // /episodes endpoint returns an empty list — common for currently-airing
  // titles whose per-episode breakdown hasn't been filled in on MAL yet,
  // even though the season entry itself exists. AniList tends to have
  // nextAiringEpisode populated for these from its own airing schedule.
  static const _aniListNextEpisodeQuery = r'''
query ($idMal: Int) {
  Media(idMal: $idMal, type: ANIME) {
    episodes
    nextAiringEpisode { episode }
  }
}
''';

  /// Returns the latest episode number that has already aired, using
  /// AniList's airing schedule. `nextAiringEpisode.episode` is the episode
  /// NOT yet aired, so the latest aired one is that minus 1. If the show
  /// has no more upcoming episodes (finished airing), falls back to the
  /// total `episodes` count. Returns null if AniList has neither field
  /// populated — callers should treat that as "still unknown", not guess.
  static Future<int?> fetchLatestAiredEpisodeNumber(String malId) async {
    final idMal = int.tryParse(malId);
    if (idMal == null) return null;
    try {
      final data = await _aniListQuery(_aniListNextEpisodeQuery, {'idMal': idMal});
      final media = data?['Media'] as Map<String, dynamic>?;
      if (media == null) return null;
      final nextEp = (media['nextAiringEpisode']
          as Map<String, dynamic>?)?['episode'] as num?;
      if (nextEp != null && nextEp.toInt() > 1) return nextEp.toInt() - 1;
      final totalEpisodes = (media['episodes'] as num?)?.toInt();
      return totalEpisodes;
    } catch (e) {
      // ignore: avoid_print
      print('[fetchLatestAiredEpisodeNumber] AniList query FAILED for idMal=$idMal: $e');
      return null;
    }
  }

  static Future<List<AnimeModel>> _fetchAnimeRecommendationsFromAniList(String malId) async {
    final idMal = int.tryParse(malId);
    if (idMal == null) return const [];
    final data = await _aniListQuery(_aniListRecoQuery, {'idMal': idMal});
    final media = data?['Media'] as Map<String, dynamic>?;
    final nodes =
        (media?['recommendations'] as Map<String, dynamic>?)?['nodes'] as List<dynamic>? ?? [];

    final result = <AnimeModel>[];
    for (final n in nodes) {
      final rec = (n as Map<String, dynamic>)['mediaRecommendation'] as Map<String, dynamic>?;
      if (rec == null) continue;
      final id = rec['idMal']?.toString() ?? '';
      if (id.isEmpty) continue;
      final t = rec['title'] as Map<String, dynamic>? ?? {};
      final title = (t['english'] as String?) ?? (t['romaji'] as String?) ?? 'Unknown';
      final cover = rec['coverImage'] as Map<String, dynamic>? ?? {};
      final image = (cover['extraLarge'] as String?) ??
          (cover['large'] as String?) ??
          'https://placehold.co/600x800/png?text=No+Image';
      final score = ((rec['averageScore'] as num?)?.toDouble() ?? 0.0) / 10.0;

      result.add(AnimeModel(
        id: id,
        title: title,
        imageUrl: image,
        rating: score,
