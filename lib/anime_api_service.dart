  static Future<JikanAnimeDetail> _fetchAnimeDetailFromJikan(String malId) async {
    final res = await _jikanGet('$_jikanBase/anime/$malId/full');
    final decoded = jsonDecode(res.body) as Map<String, dynamic>;
    final data = decoded['data'] as Map<String, dynamic>? ?? {};

    final titleEn = (data['title_english'] as String?)?.trim();
    final titleDefault = (data['title'] as String?)?.trim();
    final title = (titleEn?.isNotEmpty == true)
        ? titleEn!
        : (titleDefault?.isNotEmpty == true ? titleDefault! : 'Unknown Title');

    final synopsis = (data['synopsis'] as String?)?.trim() ?? '';
    final score = (data['score'] as num?)?.toDouble() ?? 0.0;
    final rank = (data['rank'] as num?)?.toInt();
    final episodes = (data['episodes'] as num?)?.toInt();
    final status = (data['status'] as String?)?.trim() ?? 'Unknown';

    final genres = <String>[
      ...((data['genres'] as List<dynamic>? ?? [])
          .whereType<Map<String, dynamic>>()
          .map((g) => (g['name'] as String?)?.trim())
          .whereType<String>()),
      ...((data['explicit_genres'] as List<dynamic>? ?? [])
          .whereType<Map<String, dynamic>>()
          .map((g) => (g['name'] as String?)?.trim())
          .whereType<String>()),
    ];

    final studios = (data['studios'] as List<dynamic>? ?? [])
        .whereType<Map<String, dynamic>>()
        .map((s) => (s['name'] as String?)?.trim())
        .whereType<String>()
        .toList();

    final images = data['images'] as Map<String, dynamic>? ?? {};
    final jpg = images['jpg'] as Map<String, dynamic>? ?? {};
    final largeImageUrl = (jpg['large_image_url'] as String?) ??
        (jpg['image_url'] as String?) ??
        'https://placehold.co/600x800/png?text=No+Image';

    final trailer = data['trailer'] as Map<String, dynamic>?;
    final trailerYoutubeId = (trailer?['youtube_id'] as String?);

    // Relations
    final relationsRaw = data['relations'] as List<dynamic>? ?? [];
    final relations = <RelatedAnimeModel>[];
    for (final rel in relationsRaw) {
      final r = rel as Map<String, dynamic>;
      final relationType = (r['relation'] as String?)?.trim() ?? 'Related';
      final entries = r['entry'] as List<dynamic>? ?? [];
