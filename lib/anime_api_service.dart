  static Future<List<CharacterModel>?> _fetchAnimeCharactersFromAniList(String malId) async {
    final idMal = int.tryParse(malId);
    if (idMal == null) return null;
    final data = await _aniListQuery(_aniListCharactersQuery, {'idMal': idMal});
    final media = data?['Media'] as Map<String, dynamic>?;
    if (media == null) return null;
    final edges = (media['characters'] as Map<String, dynamic>?)?['edges'] as List<dynamic>? ?? [];

    final characters = <CharacterModel>[];
    final voiceActors = <VoiceActorModel>[];

    for (final edge in edges) {
      final e = edge as Map<String, dynamic>;
      final node = e['node'] as Map<String, dynamic>? ?? {};
      final charId = node['id']?.toString() ?? '';
      if (charId.isEmpty) continue;
      final charName = ((node['name'] as Map<String, dynamic>?)?['full'] as String?)?.trim() ?? 'Unknown';
      final charImage = ((node['image'] as Map<String, dynamic>?)?['large'] as String?) ??
          'https://placehold.co/256x256/png?text=?';
      final roleRaw = (e['role'] as String?)?.trim() ?? 'SUPPORTING';
      final role = roleRaw == 'MAIN' ? 'Main' : (roleRaw == 'BACKGROUND' ? 'Background' : 'Supporting');

      final vaListRaw = e['voiceActors'] as List<dynamic>? ?? [];
      final charVAs = <CharacterVoiceActor>[];
      for (final va in vaListRaw) {
        final vaMap = va as Map<String, dynamic>;
        final vaName = ((vaMap['name'] as Map<String, dynamic>?)?['full'] as String?)?.trim() ?? 'Unknown';
        final vaImage = ((vaMap['image'] as Map<String, dynamic>?)?['large'] as String?) ??
            'https://placehold.co/256x256/png?text=VA';

        charVAs.add(CharacterVoiceActor(name: vaName, language: 'Japanese', imageUrl: vaImage));

        // Build a Jikan-shaped map so the existing VoiceActorModel.fromJson
        // parser (which expects Jikan's native format) can be reused as-is.
        voiceActors.add(VoiceActorModel.fromJson(
          {
            'language': 'Japanese',
            'person': {
              'name': vaName,
              'images': {
                'jpg': {'image_url': vaImage},
              },
            },
          },
          characterName: charName,
          characterImageUrl: charImage,
        ));
      }

      characters.add(CharacterModel(
        malId: charId, name: charName, imageUrl: charImage,
        role: role, voiceActors: charVAs));
    }

    if (characters.isEmpty) return null;
    _vaCache[malId] = voiceActors;
    return characters;
